# -*- coding: utf-8 -*-
"""Rebuild the public surface-temperature CSV from the stated study inputs.

This intentionally contains no energy-price, operating-hours, CO2 or payback
assumptions. It reproduces only the three component-level records deposited for
the engrXiv/Zenodo surface-temperature study.
"""

from __future__ import annotations

import argparse
import csv
import io
from pathlib import Path


AMBIENT_C = 25.0
CONDUCTIVITY_W_MK = 0.045
INSULATION_THICKNESS_M = 0.100
EXTERNAL_COEFFICIENT_W_M2K = 10.0
AREA_ALLOWANCE = 1.12
TOUCH_SAFE_LIMIT_C = 45.0

ELEMENTS = (
    ("Front door", "flat (door)", 2.08, 96, 30),
    ("Boiler burner flange", "ring/flange", 0.76, 146, 30),
    ("Steam valves", "valve+piping", 0.40, 190, 36),
)

FIELDS = (
    "element",
    "geometry",
    "cad_area_m2",
    "surface_area_m2_plus12pct",
    "bare_surface_C_FLIR",
    "insulated_surface_C_FLIR",
    "insulated_surface_C_model_ISO12241_100mm",
    "ambient_C",
    "touch_safe_ISO13732_1",
    "excess_temp_reduction_pct",
)


def model_surface_c(bare_surface_c: float) -> float:
    conductance = CONDUCTIVITY_W_MK / INSULATION_THICKNESS_M
    return (
        bare_surface_c * conductance
        + AMBIENT_C * EXTERNAL_COEFFICIENT_W_M2K
    ) / (conductance + EXTERNAL_COEFFICIENT_W_M2K)


def rows() -> list[dict[str, object]]:
    result = []
    for element, geometry, cad_area, bare_c, insulated_c in ELEMENTS:
        excess_reduction = (
            (bare_c - insulated_c) / (bare_c - AMBIENT_C) * 100.0
        )
        result.append(
            {
                "element": element,
                "geometry": geometry,
                "cad_area_m2": cad_area,
                "surface_area_m2_plus12pct": round(cad_area * AREA_ALLOWANCE, 2),
                "bare_surface_C_FLIR": bare_c,
                "insulated_surface_C_FLIR": insulated_c,
                "insulated_surface_C_model_ISO12241_100mm": round(
                    model_surface_c(bare_c), 1
                ),
                "ambient_C": AMBIENT_C,
                "touch_safe_ISO13732_1": (
                    "yes" if insulated_c <= TOUCH_SAFE_LIMIT_C else "no"
                ),
                "excess_temp_reduction_pct": round(excess_reduction, 1),
            }
        )
    return result


def render_csv() -> bytes:
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=FIELDS, lineterminator="\r\n")
    writer.writeheader()
    writer.writerows(rows())
    return stream.getvalue().encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).parent / "data" / "surface_temperatures.csv",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Compare the generated bytes with --output without writing.",
    )
    args = parser.parse_args()
    generated = render_csv()
    if args.check:
        current = args.output.read_bytes()
        if current != generated:
            print(f"FAIL: {args.output} differs from reproducible output")
            return 1
        print(f"PASS: {args.output} matches reproducible output ({len(generated)} bytes)")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(generated)
    print(f"Wrote {args.output} ({len(generated)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
